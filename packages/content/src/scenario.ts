import { z } from "zod";
import { materialIds, productIds } from "./catalog.ts";
import { regionIds } from "./regions.ts";

/** The two fictional news sources (R11). */
export const newsSources = {
  serious: "Le Quotidien du Continent",
  tabloid: "L'Écho Choc",
} as const;
export type NewsSource = keyof typeof newsSources;

const region = z.enum(regionIds).nullable();

export const newsSchema = z.object({
  id: z.string(),
  day: z.int().positive(),
  source: z.enum(["serious", "tabloid"]),
  /** Region the news is about; visible to everyone anyway. */
  region,
  title: z.string(),
  body: z.string(),
});
export type ScenarioNews = z.infer<typeof newsSchema>;

/** Which suppliers an effect targets. */
const supplierTarget = z.object({
  supplierIds: z.array(z.string()).optional(),
  material: z.enum(materialIds).optional(),
  region: z.enum(regionIds).optional(),
});

/** Effects on clearly defined parameters (R12). `days` overrides the event duration. */
export const effectSchema = z.discriminatedUnion("kind", [
  z.object({
    kind: z.literal("demand"),
    region,
    productId: z.enum(productIds).nullable(),
    factor: z.number().nonnegative(),
    days: z.int().positive().optional(),
  }),
  z.object({
    kind: z.literal("supplierOutage"),
    target: supplierTarget,
    days: z.int().positive().optional(),
  }),
  z.object({
    kind: z.literal("supplierPrice"),
    target: supplierTarget,
    factor: z.number().positive(),
    days: z.int().positive().optional(),
  }),
  z.object({
    kind: z.literal("supplierStock"),
    target: supplierTarget,
    factor: z.number().positive().max(1),
    days: z.int().positive().optional(),
  }),
  z.object({
    kind: z.literal("transportDelay"),
    region: z.enum(regionIds),
    extraDays: z.int().positive(),
    days: z.int().positive().optional(),
  }),
  /** Permanent change of a region's base wage (new hires and the social reference). */
  z.object({ kind: z.literal("wage"), region: z.enum(regionIds), factor: z.number().positive() }),
  /** Machines of companies settled in the region stop for a few days, without repair. */
  z.object({ kind: z.literal("breakdown"), region: z.enum(regionIds), days: z.int().positive() }),
  /** Moves the demand ramp of a tier (negative = earlier). */
  z.object({
    kind: z.literal("recovery"),
    tier: z.union([z.literal(2), z.literal(3)]),
    shiftDays: z.int(),
  }),
]);
export type ScenarioEffect = z.infer<typeof effectSchema>;

export const eventSchema = z.object({
  id: z.string(),
  day: z.int().positive(),
  title: z.string(),
  /** Duration of the effects in days; null = permanent or instantaneous. */
  durationDays: z.int().positive().nullable(),
  effects: z.array(effectSchema),
});
export type ScenarioEvent = z.infer<typeof eventSchema>;

