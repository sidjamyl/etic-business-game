export const auctionRewardSchema = z.discriminatedUnion("kind", [
  /** Multiplies the output of every machine of the winner, permanently. */
  z.object({ kind: z.literal("outputBoost"), factor: z.number().positive() }),
  /** Multiplies every shipping cost of the winner, permanently. */
  z.object({ kind: z.literal("shippingDiscount"), factor: z.number().positive() }),
  /** Gives the winner a machine, delivered immediately. */
  z.object({ kind: z.literal("machine"), machineTypeId: z.string() }),
]);
export type AuctionReward = z.infer<typeof auctionRewardSchema>;

