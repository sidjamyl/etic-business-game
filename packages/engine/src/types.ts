import type {
  Branch,
  CardId,
  ItemId,
  JobId,
  LedgerCategory,
  MaterialId,
  NewsSource,
  ProductId,
  RegionId,
  TransportOption,
} from "@etic/content";
import type { RngState } from "./rng.ts";

export type GameStatus = "lobby" | "running" | "paused" | "ended";

export interface GameConfig {
  /** Sub-steps per simulated day (N5: 4, i.e. every 15 s at real speed). */
  stepsPerDay: number;
  /** Final countdown length in simulated days (R19). */
  countdownDays: number;
}

/** Simulated time: `day` starts at 1, `step` goes from 0 to stepsPerDay - 1. */
export interface SimTime {
  day: number;
  step: number;
}

export interface Member {
  userId: string;
  name: string;
}

export type ActivityKind = "system" | "decision" | "event";

/** One line of a team's activity log (P11, stories 116–117). */
export interface ActivityEntry {
  id: number;
  day: number;
  step: number;
  kind: ActivityKind;
  message: string;
  /** First name of the member who acted, for decisions. */
  actor?: string;
}

export interface SecretCard {
  id: CardId;
  used: boolean;
}

/** What the spying card revealed, frozen at the moment it was played (N18). */
export interface SpyReport {
  targetTeamId: string;
  companyName: string;
  day: number;
  cash: number;
  debt: number;
  reputation: number;
  tier: number;
  branch: string | null;
  inventory: Partial<Record<ItemId, number>>;
  machines: { typeId: string; efficiency: number; status: string }[];
  employees: { operators: number; logisticians: number; averageEfficiency: number };
  pendingOrders: number;
  acceptedOrders: number;
  prices: Partial<Record<RegionId, Partial<Record<ProductId, number>>>>;
  recentBlackMarketTraces: number;
}

export interface CardEffects {
  spyReport: SpyReport | null;
  /** Amnesty shield: cancels the next accusation until this day (N18). */
  amnestyUntilDay: number | null;
}

/** Goods ordered from a supplier, on their way to the warehouse (R4). */
export type InboundShipment = {
  id: string;
  supplierId: string;
  arrivesOnDay: number;
  /** "waiting-space" once arrived while the warehouse is full (R9). */
  status: "in-transit" | "waiting-space";
} & (
  | { kind: "material"; item: ItemId; quantity: number }
  | { kind: "machine"; machineTypeId: string }
);

export type MachineStatus =
  | "stopped"
  | "idle"
  | "running"
  | "waiting-materials"
  | "waiting-operators"
  | "waiting-space"
  | "maintenance"
  | "strike";

/** A machine owned by a company (R5, N9). Operators are assigned on the employee side. */
export interface MachineState {
  id: string;
  typeId: string;
  /** Output multiplier, from 1 (new) down to the wear floor. */
  efficiency: number;
  status: MachineStatus;
  /** Production queue: one product, a number of cycles still to start. */
  job: { productId: ProductId; cyclesRemaining: number } | null;
  /**
   * Cycle in progress. Materials were consumed and the output computed at its start, so
   * players know what a cycle will produce.
   */
  cycle: { productId: ProductId; output: number; stepsDone: number; stepsTotal: number } | null;
  /** Finished output waiting for warehouse space (R9). */
  pendingOutput: { productId: ProductId; quantity: number } | null;
  maintenanceUntilDay: number | null;
  /** Forced stop without repair (event breakdown, sabotage). */
  stoppedUntilDay: number | null;
  /** Set when the machine works during the day; drives wear at the next day. */
  ranToday: boolean;
}

/** An employee (R6). Hired employees arrive after a delay. */
export interface Employee {
  id: string;
  job: JobId;
  /** Wage per 30 simulated days, in crédits. */
  wage: number;
  /** Output multiplier from 1 down to the HR floor; 0 while on strike is applied separately. */
  efficiency: number;
  hiredOnDay: number;
  arrivesOnDay: number;
  lastRaiseDay: number;
  /** Machine the operator works on (Production module). */
  machineId: string | null;
}

export interface HrState {
  nextPayrollDay: number;
  /** Wages owed and not yet paid; the staff is on strike while it is positive (R6). */
  unpaidWages: number;
  /** First day of the current strike, for the collective resignation (N25). */
  strikeStartDay: number | null;
  /** Facts for the social indicator (R17). */
  strikeDays: number;
  massResignations: number;
  layoffs: number;
  /** Sum over days and employees of wage / regional base wage, and the matching employee-days. */
  wageRatioSum: number;
  employeeDays: number;
}

export type OrderStatus = "pending" | "accepted" | "shipping";

/** A customer order generated by simulated demand (R7, N10). */
export interface CustomerOrder {
  id: string;
  productId: ProductId;
  region: RegionId;
  quantity: number;
  /** Price per unit, locked when the order is created. */
  unitPrice: number;
  createdDay: number;
  /** Last day the order can be accepted. */
  expiresOnDay: number;
  /** Last day for an on-time delivery. */
  deadlineDay: number;
  status: OrderStatus;
}

/** A shipment of finished goods (R8, N11). Goods leave the warehouse when it departs. */
export interface Shipment {
  id: string;
  orderId: string;
  productId: ProductId;
  destination: RegionId;
  quantity: number;
  option: TransportOption;
  cost: number;
  status: "queued" | "in-transit";
  /** Travel days once departed, including event delays. */
  travelDays: number;
  departedDay: number | null;
  arrivesOnDay: number | null;
}

/** A demand modifier set by events (R12), e.g. a scandal sets factor 0 on a product. */
export interface DemandModifier {
  id: string;
  region: RegionId | null;
  productId: ProductId | null;
  factor: number;
  untilDay: number | null;
}

/** One cash movement (R16, N12): positive = income, negative = expense. */
export interface LedgerEntry {
  id: number;
  day: number;
  category: LedgerCategory;
  amount: number;
  label: string;
}

export interface FinanceState {
  /** Everything owed to the bank: principal + capitalized interest. */
  debt: number;
  /** Borrowed principal still owed; limited by the loan ceiling. */
  principal: number;
  nextInterestDay: number;
  /** Latest entries only (see financeRules.ledgerLimit). */
  ledger: LedgerEntry[];
  /** Totals per category over the whole game. */
  totals: Partial<Record<LedgerCategory, number>>;
}

/** A marketing campaign (R10, N14); null region / product = all regions / whole range. */
export interface Campaign {
  id: string;
  region: RegionId | null;
  productId: ProductId | null;
  startDay: number;
  /** Last day of effect. */
  endDay: number;
  cost: number;
}

/** Permanent advantages won at auctions (R12, N16). */
export interface Perks {
  /** Multiplier on every machine's output. */
  outputFactor: number;
  /** Multiplier on every shipping cost. */
  shippingFactor: number;
}

export interface AuctionBid {
  amount: number;
  /** Order of the bid at its current amount, for ties (earliest wins). */
  order: number;
}

export interface AuctionState {
  id: string;
  status: "open" | "closed";
  opensDay: number;
  /** Last day bids are accepted. */
  closesDay: number;
  /** Sealed bids by team: never shown to other teams. */
  bids: Record<string, AuctionBid>;
  winnerTeamId: string | null;
}

/** A black-market deal remembered for 30 days, with the illicit gain it brought (R13). */
export interface BlackMarketTrace {
  day: number;
  gain: number;
}

export interface BlackMarketTeamState {
  traces: BlackMarketTrace[];
  bannedUntilDay: number | null;
  soldToday: Partial<Record<ProductId, number>>;
  /** Day of the last accusation against each team, for the cooldown. */
  lastAccusations: Record<string, number>;
  /** Private investigation results. */
  investigations: { targetTeamId: string; day: number; proofFound: boolean }[];
  /** Facts for the impact indicators (R17). */
  purchasedUnits: number;
  soldUnits: number;
  convictions: number;
}

/** Goods exchanged between companies (R15, N19). */
export type TradeGood =
  | { kind: "item"; item: ItemId; quantity: number }
  | { kind: "machine"; machineId: string; typeId: string };

export interface TradeOffer {
  id: string;
  sellerId: string;
  buyerId: string;
  good: TradeGood;
  /** Total price in crédits, paid into escrow on acceptance. */
  price: number;
  option: TransportOption;
  shippingPaidBy: "seller" | "buyer";
  createdDay: number;
  expiresOnDay: number;
}

/** Goods on their way between companies; the escrow goes to the seller on arrival. */
export interface TradeShipment {
  id: string;
  kind: "contract" | "gift";
  sellerId: string;
  buyerId: string;
  good: TradeGood;
  /** Machine travelling with its state (efficiency kept). */
  machine: MachineState | null;
  escrow: number;
  arrivesOnDay: number;
}

/** Volume-weighted facts behind the impact indicators (R17, N20). */
export interface ImpactFacts {
  purchases: { units: number; environmentalSum: number; socialSum: number; lowRatedUnits: number };
  production: { units: number; environmentalSum: number; ferroniaUnits: number };
  transport: { units: number; environmentalSum: number; expressUnits: number };
}

/** One line of the final ranking (R18). */
export interface RankingEntry {
  rank: number;
  teamId: string;
  companyName: string;
  netCash: number;
  economic: number;
  environmental: number;
  social: number;
  impact: number;
  final: number;
}

/** Final results and the organizer-driven reveal (N21). */
export interface ResultsState {
  ranking: RankingEntry[];
  /** Teams revealed so far, from the last to the first. */
  revealedCount: number;
  breakdownShown: boolean;
}

/** Product tiers reached by a company (R1, R2). */
export interface ProgressionState {
  unlockedTier: 1 | 2 | 3;
  /** Tier-3 branch, chosen for good when investing in tier 3. */
  branch: Branch | null;
  project: { tier: 2 | 3; branch: Branch | null; completesOnDay: number } | null;
}

export interface WarehouseState {
  capacity: number;
  expansion: { completesOnDay: number; amount: number } | null;
}

export interface TeamState {
  id: string;
  /** Team name given by the organizer (e.g. "Équipe 1"). */
  name: string;
  /** Join code handed out by the organizer (P7). */
  joinCode: string;
  /** Company name chosen by the team in the lobby (R21). */
  companyName: string | null;
  /** Home region chosen in the lobby, permanent once the game starts (R3). */
  region: RegionId | null;
  members: Record<string, Member>;
  cash: number;
  /** Cash locked by auction bids: not spendable (N16). */
  reservedCash: number;
  perks: Perks;
  finance: FinanceState;
  /** Secret card dealt at the start (R14). */
  card: SecretCard | null;
  cardEffects: CardEffects;
  /** Goods in the warehouse: raw materials and finished products. */
  inventory: Partial<Record<ItemId, number>>;
  inbound: Record<string, InboundShipment>;
  machines: Record<string, MachineState>;
  warehouse: WarehouseState;
  employees: Record<string, Employee>;
  hr: HrState;
  /** Selling prices per region and product; no price = not selling there (R7). */
  prices: Partial<Record<RegionId, Partial<Record<ProductId, number>>>>;
  orders: Record<string, CustomerOrder>;
  /** Finished products reserved by accepted orders (O2). */
  reserved: Partial<Record<ProductId, number>>;
  autoAccept: Partial<Record<ProductId, boolean>>;
  /** 0 to 100 (R7). */
  reputation: number;
  shipments: Record<string, Shipment>;
  progression: ProgressionState;
  campaigns: Record<string, Campaign>;
  blackMarket: BlackMarketTeamState;
  impact: ImpactFacts;
  /** Secrets found by the company (R20). */
  badges: string[];
  /** Shipments prepared today by the logisticians (R8). */
  preparedToday: number;
  /** Fractional demand not yet turned into orders, per "region:product". */
  demandCarry: Record<string, number>;
  /** Running totals used by other modules (impact, progression, score). */
  stats: {
    produced: Partial<Record<ProductId, number>>;
    /** Units ordered by customers per day and "region:product", last days only. */
    orderHistory: Record<string, Record<string, number>>;
    /** Units delivered and paid, per product (progression milestones, R2). */
    sold: Partial<Record<ProductId, number>>;
    revenue: number;
    lateDeliveries: number;
    failedOrders: number;
    /** Units shipped per transport option (environmental indicator, R17). */
    shippedUnits: Partial<Record<TransportOption, number>>;
  };
  log: ActivityEntry[];
}

export interface SupplierMarketState {
  stock: number;
  nextRestockDay: number;
  /** Multiplier set by events (R4: prices only change through events). */
  priceFactor: number;
}

export interface EquipmentMarketState {
  stock: Record<string, number>;
  nextRestockDay: number;
  priceFactor: number;
}

/** Shared world state (suppliers' stock is shared by every team, R4). */
export interface MarketState {
  suppliers: Record<string, SupplierMarketState>;
  equipment: Record<string, EquipmentMarketState>;
  /** People still available for hire in each region (R6). */
  laborPool: Partial<Record<RegionId, number>>;
  /** Demand modifiers from events (R12). */
  demandModifiers: Record<string, DemandModifier>;
  /** Days by which events moved the recovery of tiers 2 and 3 (negative = earlier). */
  recoveryShiftDays: { 2: number; 3: number };
  supplierEffects: Record<string, SupplierEffect>;
  transportDelays: Record<string, TransportDelay>;
  /** Permanent base wage multipliers per region (events). */
  wageFactor: Partial<Record<RegionId, number>>;
  /** Supplier priority cards: on `day`, only `teamId` may buy from the supplier (N18). */
  supplierPriority: Record<string, { teamId: string; day: number }>;
  /** Black-market stock, shared by every team (R13). */
  blackMarket: { stock: Partial<Record<MaterialId, number>>; nextRestockDay: number };
}

/** A published news item (R11). `origin` is never sent to players. */
export interface NewsItem {
  id: number;
  day: number;
  step: number;
  source: NewsSource;
  region: RegionId | null;
  title: string;
  body: string;
  origin: { kind: "scenario"; ref: string } | { kind: "card"; teamId: string };
}

/** Supplier conditions set by an event (R12); combined when several overlap. */
export interface SupplierEffect {
  supplierIds: string[];
  priceFactor: number;
  stockFactor: number;
  outage: boolean;
  untilDay: number | null;
}

export interface TransportDelay {
  region: RegionId;
  extraDays: number;
  untilDay: number | null;
}

export interface ScenarioState {
  /** Scenario news and events already published or fired, by id. */
  done: Record<string, true>;
  /** Events whose effects are running. */
  active: Record<string, { title: string; startDay: number; endDay: number | null }>;
}

export interface Announcement {
  id: number;
  day: number;
  step: number;
  message: string;
}

export interface GameState {
  schemaVersion: 1;
  id: string;
  config: GameConfig;
  status: GameStatus;
  time: SimTime;
  /** Last simulated day; the game ends when this day is over. Null = no scheduled end. */
  endDay: number | null;
  rng: RngState;
  /** Monotonic counter for ids created inside the state. */
  nextId: number;
  /** Number of journal entries (accepted commands and steps) applied so far. */
  journalSeq: number;
  /** Maximum members per team (O4). */
  memberCap: number;
  teams: Record<string, TeamState>;
  market: MarketState;
  news: NewsItem[];
  scenario: ScenarioState;
  auctions: Record<string, AuctionState>;
  /** Private between the two companies involved (and the organizer). */
  trades: { offers: Record<string, TradeOffer>; shipments: Record<string, TradeShipment> };
  /** Companies that found each secret, in order (R20). */
  easterEggs: Record<string, string[]>;
  /** Filled when the game ends (R18, R19). */
  results: ResultsState | null;
  announcements: Announcement[];
}

/** Who sends a command. Resolved by the server from the session, never from the client. */
export type Actor =
  | { kind: "organizer"; userId: string; name: string }
  /** A signed-in person acting before belonging to a team (joining with a code). */
  | { kind: "player"; userId: string; name: string }
  | { kind: "team"; teamId: string; userId: string; name: string };

export interface Command {
  type: string;
  payload?: unknown;
}

export type RefusalCode =
  | "UNKNOWN_COMMAND"
  | "INVALID_PAYLOAD"
  | "FORBIDDEN"
  | "GAME_NOT_STARTED"
  | "GAME_PAUSED"
  | "GAME_ENDED"
  | "INVALID_STATE"
  | "NOT_FOUND"
  | "INSUFFICIENT_FUNDS"
  | "TEAM_FULL"
  | "ALREADY_IN_TEAM"
  | "NOT_READY"
  | "OUT_OF_STOCK"
  | "ALREADY_IN_PROGRESS"
  | "POOL_EXHAUSTED"
  | "LOAN_LIMIT"
  | "BID_TOO_LOW"
  | "BANNED"
  | "COOLDOWN";

export interface Refusal {
  code: RefusalCode;
  /** French message shown to players. */
  message: string;
}

export type CommandResult = { ok: true; state: GameState } | { ok: false; refusal: Refusal };
